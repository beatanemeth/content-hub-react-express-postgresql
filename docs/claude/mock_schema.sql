-- Parent tables: no foreign keys.

-- full_name is UNIQUE so two people never share a name in the author dropdown.
CREATE TABLE person (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name text NOT NULL UNIQUE,
    email text NOT NULL UNIQUE,
    occupation text NOT NULL -- e.g., "Founder, Q Grader and roaster"
);

CREATE TABLE venue (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,        -- e.g., "Blue Bottle Cafe"
    address text NOT NULL
);

CREATE TABLE category (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label text NOT NULL UNIQUE -- e.g., "CafeStories", "BrewingTips"
);

CREATE TABLE event_category (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label text NOT NULL UNIQUE -- e.g., "Cupping Session", "Latte Art Workshop"
);

CREATE TABLE tag (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label text NOT NULL UNIQUE -- e.g., "Ritual", "Patience"
);

-- Roles of a person: one row per person at most, so person_id is the primary key.

CREATE TABLE staff (
    person_id integer PRIMARY KEY REFERENCES person (id),
    job_title text NOT NULL,
    phone text NOT NULL,
    joined_on date NOT NULL
);

CREATE TABLE founder (
    person_id integer PRIMARY KEY REFERENCES person (id),
    bio text NOT NULL
);

-- Posts and their link tables.

CREATE TABLE post (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,         -- e.g., "From a Borrowed Kitchen to a Roastery"
    summary text NOT NULL,       -- One or two sentences
    body text NOT NULL,          -- Paragraphs separated by a blank line
    author_id integer NOT NULL REFERENCES person (id),
    published_on date NOT NULL,
    updated_at timestamptz NOT NULL
);

-- ON DELETE CASCADE: deleting a post also deletes its link rows, instead of being blocked by them.
CREATE TABLE post_category (
    post_id integer REFERENCES post (id) ON DELETE CASCADE,
    category_id integer REFERENCES category (id),
    PRIMARY KEY (post_id, category_id)
);

CREATE TABLE post_tag (
    post_id integer REFERENCES post (id) ON DELETE CASCADE,
    tag_id integer REFERENCES tag (id),
    PRIMARY KEY (post_id, tag_id)
);